"""Human-review HTML rendering for acoustic annotations; independent of model inference."""
from __future__ import annotations

import html
from pathlib import Path


def report_path(name: Path) -> Path:
    """Resolve relative names beside this script, independent of the working directory."""
    name = name.expanduser()
    if not name.is_absolute():
        name = Path(__file__).resolve().parent / name
    return name if name.suffix.lower() == ".html" else name.parent / (name.name + ".html")


def write_html_report(records: list[dict], output: Path) -> None:
    """Render file, status, acoustic tags, and raw output for review."""
    def esc(value) -> str:
        return html.escape(str(value) if value is not None else "", quote=True)

    rows = []
    for record in records:
        tags = " ".join(f'<span class="tag">{esc(tag)}</span>' for tag in record.get("tags", [])) or "—"
        raw = record.get("raw_model_output", "")
        if record.get("error"):
            raw += "\n\nReview note: " + record["error"]
        rows.append(
            '<tr>'
            f'<td><code>{esc(record["file"])}</code></td>'
            f'<td>{esc(record["status"])}</td>'
            f'<td>{tags}</td>'
            f'<td><pre>{esc(raw)}</pre></td>'
            '</tr>'
        )
    models = ", ".join(dict.fromkeys(record["model"] for record in records))
    page = '''<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>VocaLocate — Generated SFX annotations</title>
<style>body{font:14px system-ui,sans-serif;margin:30px;line-height:1.45;color:#253047}
h1{font-size:24px}p{color:#555}table{border-collapse:collapse;width:100%}
th,td{border:1px solid #d9dce3;padding:10px;text-align:left;vertical-align:top}
th{background:#eef2f8;position:sticky;top:0}tr:nth-child(even){background:#f9fafb}
.tag{display:inline-block;border-radius:9px;background:#e7edf9;padding:3px 8px;margin:2px}
code{overflow-wrap:anywhere}pre{white-space:pre-wrap;max-width:360px;overflow-wrap:anywhere}
</style></head><body><h1>VocaLocate: Candidate SFX annotations</h1>
'''
    page += f'<p>Generated by {esc(models)}. These are not validated ground truth; listen and audit tags.</p>'
    page += '<table><thead><tr><th>File</th><th>Status</th><th>Acoustic tags</th><th>Raw output</th></tr></thead><tbody>'
    page += "\n".join(rows) + '</tbody></table></body></html>'
    output.write_text(page, encoding="utf-8")
